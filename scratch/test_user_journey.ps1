# ── TEST 1: Registration ───────────────────────────────────────────
Write-Host "`n--- TEST 1: User Registration ---" -ForegroundColor Yellow
$userAEmail = "user.a." + (Get-Random -Minimum 1000 -Maximum 9999) + "@acme.com"
$userAPass = "Password123!"

$regBody = @{
    firstName = "Alice"
    lastName = "Smith"
    email = $userAEmail
    password = $userAPass
    department = "ENGINEERING"
} | ConvertTo-Json

$regRes = Invoke-RestMethod -Uri "http://localhost:8080/api/auth/register" -Method Post -Body $regBody -ContentType "application/json"

Assert-Condition ($null -ne $regRes.token) "Registration returned a JWT token"
Assert-Condition ($regRes.email -eq $userAEmail) "User email matches ($userAEmail)"
Assert-Condition ($regRes.fullName -eq "Alice Smith") "User fullName is Alice Smith"
$userAId = $regRes.id
Assert-Condition ($userAId -gt 0) "User ID ($userAId) was generated by database"

# Try duplicate registration with same email
try {
    $dupRes = Invoke-RestMethod -Uri "http://localhost:8080/api/auth/register" -Method Post -Body $regBody -ContentType "application/json"
    Write-Error "Duplicate registration did not fail!"
} catch {
    Assert-Condition ($true) "Duplicate registration with same email was rejected"
}

