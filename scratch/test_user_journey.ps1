$userBEmail = "user.b." + (Get-Random -Minimum 1000 -Maximum 9999) + "@innovate.com"
$userBPass = "Password456!"

$regBBody = @{
    firstName = "Bob"
    lastName = "Jones"
    email = $userBEmail
    password = $userBPass
    department = "PRODUCTIVITY"
} | ConvertTo-Json

