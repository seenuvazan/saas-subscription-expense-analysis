$ErrorActionPreference = 'Stop'

function Assert-Condition($condition, $message) {
    if (-not $condition) {
        Write-Error "ASSERTION FAILED: $message"
    } else {
        Write-Host "  [PASS] $message" -ForegroundColor Green
    }
}

Write-Host "======================================================" -ForegroundColor Cyan
